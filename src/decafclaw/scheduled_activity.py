@overload
def extract_activity(
    path: Path,
    include_workspace_files: bool = False,
    include_errors: bool = False,
) -> tuple[str, list[str]] | tuple[str, list[str], list[str]] | tuple[str, list[str], list[str], bool, list[str]]: ...


def extract_activity(
    path: Path,
    include_workspace_files: bool = False,
    include_errors: bool = False,
) -> tuple[str, list[str]] | tuple[str, list[str], list[str]] | tuple[str, list[str], list[str], bool, list[str]]:
    """Read a conversation JSONL; return (final_assistant_text, vault_pages_touched[, workspace_files_touched][, has_error, errors])."""
    final_text = ""
    vault_touched: list[str] = []
    workspace_touched: list[str] = []
    errors: list[str] = []
    try:
        with path.open() as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except json.JSONDecodeError:
                    continue
                role = rec.get("role")
                if role == "tool":
                    tool_content = str(rec.get("content") or "")
                    if "[error:" in tool_content:
                        err_line = next(
                            (line_item.strip() for line_item in tool_content.splitlines() if "[error:" in line_item),
                            tool_content.strip(),
                        )
                        errors.append(err_line[:200])
                elif role == "assistant":
                    content = rec.get("content") or ""
                    if content and not is_status_token(content):
                        final_text = content
                    if content.startswith("[error:"):
                        errors.append(content.strip()[:200])
                    for call in rec.get("tool_calls") or []:
                        fn = (call.get("function") or {}).get("name")
                        if fn in VAULT_WRITE_TOOLS:
                            try:
                                args = json.loads((call.get("function") or {}).get("arguments") or "{}")
                            except json.JSONDecodeError:
                                continue
                            page = args.get("page")
                            if page:
                                vault_touched.append(page)
                        elif fn in WORKSPACE_WRITE_TOOLS:
                            try:
                                args = json.loads((call.get("function") or {}).get("arguments") or "{}")
                            except json.JSONDecodeError:
                                continue
                            ws_path = args.get("path")
                            if ws_path:
                                workspace_touched.append(ws_path)
                        elif fn == "send_notification":
                            try:
                                args = json.loads((call.get("function") or {}).get("arguments") or "{}")
                                if args.get("priority") in ("high", "urgent"):
                                    err_msg = args.get("message") or args.get("title") or "High-priority alert"
                                    errors.append(err_msg[:200])
                            except json.JSONDecodeError:
                                pass
    except OSError as exc:
        log.debug("Failed to read %s: %s", path, exc)
    # Deduplicate while preserving insertion order
    vault_touched = list(dict.fromkeys(vault_touched))
    workspace_touched = list(dict.fromkeys(workspace_touched))
    errors = list(dict.fromkeys(errors))
    has_error = bool(errors)
    if include_errors:
        return final_text, vault_touched, workspace_touched, has_error, errors
    if include_workspace_files:
        return final_text, vault_touched, workspace_touched
    return final_text, vault_touched


REFUSAL_MARKERS = (
    "denied by user",
    "denied on an unattended turn",
    "requires explicit confirmation",
    "blocked by security monitor",
    "[cancelled:",
    "was denied",
)


def extract_degradations(path: Path) -> list[dict]:
    """Return silent-degradation evidence from one scheduled-run archive.

    A run is degraded when a tool result contains a refusal marker and a later
    tool result in the same run does not contain ``[error:`` — the agent hit a
    refusal, worked around it, and continued. A refusal followed only by a final
    message is a visible failure, not silent degradation. Final prose is never
    consulted (#1651).
    """
    records: list[dict] = []
    try:
        with path.open() as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    except OSError as exc:
        log.debug("Failed to read %s for degradations: %s", path, exc)
        return []

    tool_names: dict[str, str] = {}
    for rec in records:
        if rec.get("role") != "assistant":
            continue
        for call in rec.get("tool_calls") or []:
            call_id = call.get("id")
            fn = (call.get("function") or {}).get("name")
            if call_id and fn:
                tool_names[call_id] = fn

    tool_results: list[tuple[int, str, str]] = []
    for index, rec in enumerate(records):
        if rec.get("role") == "tool":
            tool_results.append((index, rec.get("tool_call_id") or "", str(rec.get("content") or "")))

    degradations: list[dict] = []
    for pos, (index, call_id, content) in enumerate(tool_results):
        marker = next((candidate for candidate in REFUSAL_MARKERS if candidate in content), None)
        if marker is None:
            continue
        later_tools = [
            tool_names.get(later_id, "unknown")
            for _, later_id, later_content in tool_results[pos + 1 :]
            if "[error:" not in later_content
        ]
        if not later_tools:
            continue
        refusal_line = next(
            (line.strip() for line in content.splitlines() if marker in line),
            marker,
        )
        degradations.append(
            {
                "refusal": refusal_line[:200],
                "tool": tool_names.get(call_id, "unknown"),
                "later_tools": list(dict.fromkeys(later_tools)),
                "message_index": index,
            }
        )
    return degradations


def collect_scheduled_activity(
    config,
    hours: int = 24,
    skill_name: str | None = None,
    exclude_skill_name: str | None = None,
) -> list[dict]:
    """Gather scheduled-task activity records within `hours`.

    Returns a list of dicts:
      - skill_name: str
      - conv_id: str
      - started_at: str (ISO 8601 UTC)
      - final_message: str
      - vault_pages_touched: list[str]
      - workspace_files_touched: list[str]
      - has_error: bool
      - errors: list[str]
      - degraded: bool
      - degradations: list[dict] (refusal, tool, later_tools, message_index)
    """
    cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)
    out: list[dict] = []
    archives = sorted(iter_conversation_archives(config), key=lambda t: t[0])
    for conv_id, path in archives:
        if not conv_id.startswith("schedule-"):
            continue
        parsed = parse_scheduled_conv_id(conv_id)
        if parsed is None:
            continue
        name, ts = parsed
        if skill_name is not None and name != skill_name:
            continue
        if exclude_skill_name is not None and name == exclude_skill_name:
            continue
        if ts < cutoff:
            continue
        final, touched_vault, touched_workspace, has_error, errors = extract_activity(
            path, include_workspace_files=True, include_errors=True
        )
        degradations = extract_degradations(path)
        out.append(
            {
                "skill_name": name,
                "conv_id": conv_id,
                "started_at": ts.isoformat(),
                "final_message": final,
                "vault_pages_touched": touched_vault,
                "workspace_files_touched": touched_workspace,
                "has_error": has_error,
                "errors": errors,
                "degraded": bool(degradations),
                "degradations": degradations,
            }
        )
    return out
